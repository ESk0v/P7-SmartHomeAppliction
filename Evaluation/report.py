"""Build every table and figure for the paper from the finished runs.

    python report.py        # writes results/results.md, results/*.csv, results/fig_monthly_saving.*
"""
import json

import numpy as np
import pandas as pd

from common import HOUSES, RESULTS, RUNS, SCENARIOS
from run_all import POLICIES, TIGHT_FUSE
from simulator import Config

DEVICES = ["washing_machine", "dishwasher", "ev", "total"]
LABEL = {"naive": "Naive", "night": "Night timer", "mpc_sn": "MPC-SN", "mpc_k24": "MPC-K24", "pf": "Perfect foresight",
         "washing_machine": "Washing machine", "dishwasher": "Dishwasher", "ev": "EV", "total": "Total"}


SETTINGS = [("4 h deadline", {"deadline_h": 4}, {"deadline_h": 4}), ("8 h deadline (main)", {}, {}),
            ("12 h deadline", {"deadline_h": 12}, {"deadline_h": 12}),
            ("No fuse limit", {"fuse_kw": None}, {}), (f"Tight fuse {TIGHT_FUSE} kW", {"fuse_kw": TIGHT_FUSE}, {})]

# Figure style. Policy colours are fixed per policy (validated colour-blind safe); each policy also has
# its own marker so the figures still read in greyscale print.
COL = {"naive": "#2a78d6", "night": "#eb6834", "mpc_sn": "#1baf7a"}
MARK = {"naive": "o", "night": "s", "mpc_sn": "D"}
INK, MUTED, GRID = "#1f2328", "#6b7280", "#e5e7eb"
SHOWN = ["naive", "night", "mpc_sn"]          # MPC-K24 is indistinguishable from MPC-SN in a figure


def load(policy, **kw):
    """{house: summary} for one policy and setting."""
    out = {}
    for h in HOUSES:
        f = RUNS / Config(h, policy, **kw).name / "summary.json"
        if not f.exists():
            raise SystemExit(f"missing run {f.parent.name}: run run_all.py first")
        out[h] = json.loads(f.read_text())
    return out


def spread(values, digits=0):
    v = np.asarray(list(values), float)
    return f"{v.mean():.{digits}f} [{v.min():.{digits}f}; {v.max():.{digits}f}]"


def md(df):
    rows = ["| " + " | ".join(map(str, df.columns)) + " |", "|" + " --- |" * len(df.columns)]
    rows += ["| " + " | ".join(map(str, r)) + " |" for r in df.itertuples(index=False)]
    return "\n".join(rows)


def saving(mpc, base, dev="total"):
    """Per household: DKK saved, and % of the baseline cost of that device."""
    dkk = np.array([base[h]["cost"][dev] - mpc[h]["cost"][dev] for h in HOUSES])
    ref = np.array([base[h]["cost"][dev] for h in HOUSES])
    with np.errstate(divide="ignore", invalid="ignore"):
        pct = np.where(np.abs(ref) > 1e-9, 100 * dkk / ref, np.nan)
    return dkk, pct


def captured(mpc, base, pf, dev="total"):
    """Per household: share of the possible saving (baseline -> perfect foresight) that the MPC achieves, in %."""
    return np.array([100 * (base[h]["cost"][dev] - mpc[h]["cost"][dev]) / (base[h]["cost"][dev] - pf[h]["cost"][dev])
                     for h in HOUSES])


def main():
    RESULTS.mkdir(exist_ok=True)
    main_runs = {p: load(p) for p in POLICIES}
    text = ["# Evaluation results", "",
            "Generated by `report.py`. Values are mean [min; max] across the ten households, DKK per year, "
            "at actual DK1 spot prices (no tariffs, taxes or VAT).", ""]

    # ---- Table I: cost per device and policy, saving of MPC-SN against both baselines
    rows = []
    for d in DEVICES:
        r = {"Device": LABEL[d], "kWh/year": spread(main_runs["naive"][h]["kwh"][d] for h in HOUSES)}
        for p in POLICIES:
            r[f"{LABEL[p]} DKK"] = spread(main_runs[p][h]["cost"][d] for h in HOUSES)
        for p in POLICIES:
            kwh = sum(main_runs[p][h]["kwh"][d] for h in HOUSES)
            r[f"{LABEL[p]} DKK/kWh"] = f"{sum(main_runs[p][h]['cost'][d] for h in HOUSES) / kwh:.3f}"
        for b in ("naive", "night"):
            dkk, pct = saving(main_runs["mpc_sn"], main_runs[b], d)
            r[f"MPC-SN saving vs {LABEL[b]} DKK"] = spread(dkk)
            r[f"MPC-SN saving vs {LABEL[b]} %"] = spread(pct[~np.isnan(pct)], 1)
        for b in ("naive", "night"):
            r[f"MPC-SN share of possible saving vs {LABEL[b]} %"] = spread(captured(main_runs["mpc_sn"], main_runs[b], main_runs["pf"], d), 1)
        rows.append(r)
    t1 = pd.DataFrame(rows)
    t1.to_csv(RESULTS / "table1_main.csv", index=False)
    text += ["## Table I: main result (8 h deadline, 15 kW fuse)", "", md(t1.T.reset_index().rename(columns={"index": ""}).pipe(
        lambda x: x.set_axis(x.iloc[0], axis=1).iloc[1:])), "",
        "DKK/kWh is pooled over all households. Percentages are relative to the baseline cost of that device.", ""]

    # ---- whole-bill share and forecast gap
    for b in ("naive", "night"):
        dkk, _ = saving(main_runs["mpc_sn"], main_runs[b])
        bill = np.array([main_runs[b][h]["cost"]["total"] + main_runs[b][h]["base_cost"] for h in HOUSES])
        text.append(f"- MPC-SN saving vs {LABEL[b]} as a share of the whole spot bill including base load: {spread(100 * dkk / bill, 1)} %")
    gap, _ = saving(main_runs["mpc_k24"], main_runs["mpc_sn"])
    text += [f"- Forecast gap: MPC-K24 costs {spread(gap, 1)} DKK/year less than MPC-SN."]
    gap, _ = saving(main_runs["pf"], main_runs["mpc_sn"])
    text += [f"- Optimality gap: perfect foresight costs {spread(gap, 1)} DKK/year less than MPC-SN.",
             f"- MPC-SN captures {spread(captured(main_runs['mpc_sn'], main_runs['night'], main_runs['pf']), 1)} % of the possible saving over the night timer, "
             f"and {spread(captured(main_runs['mpc_sn'], main_runs['naive'], main_runs['pf']), 1)} % over naive.", ""]

    # ---- per household
    rows = []
    meta = pd.read_csv(SCENARIOS / "households.csv").set_index("house")
    for h in HOUSES:
        r = {"House": h, "EV user": meta.loc[h, "ev_user"], "EV months active": meta.loc[h, "ev_active_months_2019"],
             "Sessions": main_runs["naive"][h]["ev"]["sessions"],
             "Days from another week %": round(100 * meta.loc[h, "days_from_other_week"] / meta.loc[h, "days_total"], 1)}
        for d in ("washing_machine", "dishwasher", "ev"):
            r[f"{LABEL[d]} kWh"] = round(main_runs["naive"][h]["kwh"][d])
        for p in POLICIES:
            r[f"{LABEL[p]} DKK"] = round(main_runs[p][h]["cost"]["total"])
        rows.append(r)
    hh = pd.DataFrame(rows)
    hh.to_csv(RESULTS / "households.csv", index=False)
    text += ["## Households", "", md(hh), ""]

    # ---- Table II: sensitivities, MPC-SN against the night timer
    rows = []
    for name, kw_mpc, kw_base in SETTINGS:
        m, n = load("mpc_sn", **kw_mpc), load("night", **kw_base)
        dkk, pct = saving(m, n)
        pf = load("pf", **kw_base)
        own = kw_mpc.get("fuse_kw", 15.0)
        rows.append({"Setting": name, "Saving vs night timer DKK": spread(dkk), "Saving %": spread(pct, 1),
                     "Share of possible saving %": spread(captured(m, n, pf), 1),
                     "Unmet EV kWh (sum)": round(sum(m[h]["ev"]["unmet_kwh"] for h in HOUSES), 1),
                     "Steps above own limit: base load alone": sum(m[h]["fuse"]["above_own_limit"]["base_alone"] for h in HOUSES) if own else "-",
                     "Steps above own limit: caused by EV/appliances": sum(m[h]["fuse"]["above_own_limit"]["caused_by_loads"] for h in HOUSES) if own else "-",
                     "Late cycles %": round(100 * sum(m[h]["cycles"]["late"] for h in HOUSES)
                                            / max(1, sum(m[h]["cycles"]["flexible"] for h in HOUSES)), 1)})
    t2 = pd.DataFrame(rows)
    t2.to_csv(RESULTS / "table2_sensitivity.csv", index=False)
    text += ["## Table II: sensitivities (MPC-SN against the night timer, total of the shiftable loads)", "", md(t2), "",
             "The share of the possible saving uses perfect foresight with the same deadline. Perfect foresight ignores the fuse "
             "limit, so for the fuse rows it is the saving without a fuse limit.", ""]

    # ---- side effects per policy
    rows = []
    for p in POLICIES:
        s = main_runs[p]
        ses = sum(s[h]["ev"]["sessions"] for h in HOUSES)
        r = {"Policy": LABEL[p], "Unmet EV kWh (sum)": round(sum(s[h]["ev"]["unmet_kwh"] for h in HOUSES), 2),
             "Sessions with unmet energy": sum(s[h]["ev"]["sessions_unmet"] for h in HOUSES),
             "Steps above 15 kW: base load alone": sum(s[h]["fuse"]["above_15kw"]["base_alone"] for h in HOUSES),
             "Steps above 15 kW: caused by EV/appliances": sum(s[h]["fuse"]["above_15kw"]["caused_by_loads"] for h in HOUSES),
             "Max grid power kW": round(max(s[h]["fuse"]["max_kw"] for h in HOUSES), 2),
             "Cycles ending after deadline": sum(s[h]["cycles"]["late"] for h in HOUSES),
             "Over-24h sessions DKK/kWh": round(sum(s[h]["ev"]["cost_over_24h"] for h in HOUSES)
                                                / max(1e-9, sum(s[h]["ev"]["kwh_over_24h"] for h in HOUSES)), 3),
             "Other sessions DKK/kWh": round(sum(s[h]["ev"]["cost_up_to_24h"] for h in HOUSES)
                                             / max(1e-9, sum(s[h]["ev"]["kwh_up_to_24h"] for h in HOUSES)), 3)}
        rows.append(r)
    side = pd.DataFrame(rows)
    side.to_csv(RESULTS / "side_effects.csv", index=False)
    s = main_runs["naive"]
    ses = sum(s[h]["ev"]["sessions"] for h in HOUSES)
    text += ["## Side effects (main setting)", "", md(side), "",
             f"- Sessions longer than 24 h: {100 * sum(s[h]['ev']['sessions_over_24h'] for h in HOUSES) / ses:.1f} % of {ses} sessions, "
             f"{100 * sum(s[h]['ev']['kwh_over_24h'] for h in HOUSES) / sum(s[h]['kwh']['ev'] for h in HOUSES):.1f} % of the EV energy.",
             f"- Cycles: {sum(s[h]['cycles']['total'] for h in HOUSES)} in total, "
             f"{sum(s[h]['cycles']['flexible'] for h in HOUSES)} fit the 8 h window and can be shifted."]
    rows = []
    for p in ("mpc_sn", "mpc_k24"):
        for kind in ("LP", "MILP"):
            k = [main_runs[p][h]["solves"].get(kind) for h in HOUSES]
            k = [x for x in k if x]
            rows.append({"Policy": LABEL[p], "Problem": kind, "Solves": sum(x["count"] for x in k),
                         "Median ms": round(1000 * float(np.median([x["median_s"] for x in k])), 1),
                         "Largest p95 ms": round(1000 * max(x["p95_s"] for x in k), 1),
                         "Max ms": round(1000 * max(x["max_s"] for x in k), 1)})
    solves = pd.DataFrame(rows)
    solves.to_csv(RESULTS / "solve_times.csv", index=False)
    infeasible = sum(main_runs[p][h]["solves"]["infeasible"] for p in ("mpc_sn", "mpc_k24") for h in HOUSES)
    text += ["", "## Solve times", "", md(solves), "", f"Infeasible solves in the main setting: {infeasible}.", ""]

    # ---- monthly saving, MPC-SN against the night timer
    month = pd.DataFrame({h: pd.DataFrame(main_runs["night"][h]["monthly_cost"]).sum(axis=1)
                          - pd.DataFrame(main_runs["mpc_sn"][h]["monthly_cost"]).sum(axis=1) for h in HOUSES})
    month.index.name = "month"
    month.assign(mean=month.mean(axis=1)).round(2).to_csv(RESULTS / "monthly_saving.csv")
    figure(month)
    fig_price_paid(main_runs)
    fig_household_cost(main_runs)
    fig_sensitivity()
    fig_hour_of_day()
    text += ["## Figures", "",
             "- `fig_monthly_saving`: MPC-SN saving against the night timer per month (data in `monthly_saving.csv`).",
             "- `fig_price_paid`: average price paid per kWh, by device and policy; whiskers show the household range; dashed line = perfect foresight.",
             "- `fig_household_cost`: annual cost of the shiftable loads per household under each policy, with perfect foresight as a black tick.",
             "- `fig_sensitivity`: saving against the night timer for each deadline and fuse setting.",
             "- `fig_hour_of_day`: mean spot price and mean shiftable load by time of day, per policy.", ""]

    (RESULTS / "results.md").write_text("\n".join(text), encoding="utf-8")
    print("\n".join(text))


def figure(month):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    ink, muted, blue = "#1f2328", "#6b7280", "#2563a8"
    x = np.arange(len(month))
    fig, ax = plt.subplots(figsize=(3.5, 2.3))            # one IEEE column
    for h in month.columns:                                # one dot per household and month
        ax.plot(x, month[h], "o", ms=2.6, color=muted, alpha=0.45, mec="none", zorder=2)
    ax.plot(x, month.mean(axis=1), "-", lw=1.6, color=blue, zorder=3)
    ax.axhline(0, color=muted, lw=0.6, zorder=1)
    ax.annotate("mean", (x[-1], month.mean(axis=1).iloc[-1]), xytext=(4, 0), textcoords="offset points",
                color=ink, fontsize=7, va="center")
    ax.plot([], [], "o", ms=2.6, color=muted, alpha=0.6, mec="none", label="one household")
    ax.legend(frameon=False, fontsize=7, loc="upper left", handletextpad=0.2)
    ax.set_xticks(x)
    ax.set_xticklabels([pd.Timestamp(m + "-01").strftime("%b")[0] for m in month.index], fontsize=7)
    ax.set_ylabel("Saving vs night timer (DKK/month)", fontsize=7, color=ink)
    ax.tick_params(labelsize=7, colors=ink, length=2)
    ax.grid(axis="y", color="#e5e7eb", lw=0.5)
    ax.set_axisbelow(True)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)
    for s in ("left", "bottom"):
        ax.spines[s].set_color(muted)
    ax.set_xlim(-0.5, len(x) - 0.2)
    fig.tight_layout(pad=0.3)
    fig.savefig(RESULTS / "fig_monthly_saving.pdf")
    fig.savefig(RESULTS / "fig_monthly_saving.png", dpi=300)


def _axes(figsize):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    plt.rcParams.update({"font.size": 7, "axes.labelsize": 7, "xtick.labelsize": 7, "ytick.labelsize": 7,
                         "legend.fontsize": 7, "axes.edgecolor": MUTED, "text.color": INK, "axes.labelcolor": INK,
                         "xtick.color": INK, "ytick.color": INK})
    return plt, plt.figure(figsize=figsize)


def _clean(ax, grid="y"):
    ax.grid(axis=grid, color=GRID, lw=0.5)
    ax.set_axisbelow(True)
    ax.tick_params(length=2)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


def _save(fig, name):
    fig.tight_layout(pad=0.3)
    fig.savefig(RESULTS / f"{name}.pdf")
    fig.savefig(RESULTS / f"{name}.png", dpi=300)


def fig_price_paid(runs):
    """Average price paid per kWh by device and policy; whiskers = lowest and highest household."""
    plt, fig = _axes((3.5, 2.2))
    ax = fig.add_subplot()
    w = 0.26
    for j, d in enumerate(DEVICES):
        for i, p in enumerate(SHOWN):
            per_house = [runs[p][h]["cost"][d] / runs[p][h]["kwh"][d] for h in HOUSES]
            pooled = sum(runs[p][h]["cost"][d] for h in HOUSES) / sum(runs[p][h]["kwh"][d] for h in HOUSES)
            x = j + (i - 1) * w
            ax.bar(x, pooled, w - 0.03, color=COL[p], label=LABEL[p] if j == 0 else None, zorder=2)
            ax.plot([x, x], [min(per_house), max(per_house)], color=INK, lw=0.7, zorder=3)
            if p == "mpc_sn":
                ax.annotate(f"{pooled:.2f}", (x, max(per_house)), xytext=(0, 2), textcoords="offset points",
                            ha="center", fontsize=6, color=INK)
        pf = sum(runs["pf"][h]["cost"][d] for h in HOUSES) / sum(runs["pf"][h]["kwh"][d] for h in HOUSES)
        ax.plot([j - 1.5 * w, j + 1.5 * w], [pf, pf], color=INK, lw=0.9, ls=(0, (3, 2)), zorder=4,
                label="Perfect foresight" if j == 0 else None)
    ax.set_xticks(range(len(DEVICES)))
    ax.set_xticklabels([LABEL[d].replace("Washing machine", "Washing\nmachine") for d in DEVICES])
    ax.set_ylabel("Price paid (DKK/kWh)")
    ax.set_ylim(0, None)
    ax.legend(frameon=False, ncol=4, loc="upper center", bbox_to_anchor=(0.5, 1.16), columnspacing=0.8, handlelength=1.2,
              handletextpad=0.4)
    _clean(ax)
    _save(fig, "fig_price_paid")


def fig_household_cost(runs):
    """Annual cost of the shiftable loads per household, one marker per policy."""
    plt, fig = _axes((3.5, 2.6))
    ax = fig.add_subplot()
    order = sorted(HOUSES, key=lambda h: runs["naive"][h]["cost"]["total"])
    for y, h in enumerate(order):
        c = [runs[p][h]["cost"]["total"] for p in SHOWN + ["pf"]]
        ax.plot(runs["pf"][h]["cost"]["total"], y, "|", ms=7, mew=1.2, color=INK, zorder=2,
                label="Perfect foresight" if y == 0 else None)
        ax.plot([min(c), max(c)], [y, y], color=MUTED, lw=0.8, zorder=1)
        for p in SHOWN:
            ax.plot(runs[p][h]["cost"]["total"], y, MARK[p], ms=4, color=COL[p], mec="white", mew=0.5, zorder=2,
                    label=LABEL[p] if y == 0 else None)
    ax.set_yticks(range(len(order)))
    ax.set_yticklabels([f"House {h}" for h in order])
    ax.set_xlabel("Cost of shiftable loads (DKK/year)")
    ax.set_xlim(0, None)
    ax.legend(frameon=False, ncol=4, loc="upper center", bbox_to_anchor=(0.42, 1.12), columnspacing=0.7, handletextpad=0.2)
    _clean(ax, "x")
    _save(fig, "fig_household_cost")


def fig_sensitivity():
    """Saving of MPC-SN against the night timer per setting: mean, household range and one dot per household."""
    plt, fig = _axes((3.5, 1.9))
    ax = fig.add_subplot()
    for y, (name, kw_mpc, kw_base) in enumerate(SETTINGS[::-1]):
        dkk, _ = saving(load("mpc_sn", **kw_mpc), load("night", **kw_base))
        ax.plot(dkk, [y] * len(dkk), "o", ms=2.4, color=MUTED, alpha=0.45, mec="none", zorder=1)
        ax.plot([dkk.min(), dkk.max()], [y, y], color=INK, lw=0.7, zorder=2)
        ax.plot(dkk.mean(), y, MARK["mpc_sn"], ms=4.5, color=COL["mpc_sn"], mec="white", mew=0.5, zorder=3)
        ax.annotate(f"{dkk.mean():.0f}", (dkk.mean(), y), xytext=(0, 4), textcoords="offset points", ha="center", fontsize=6)
    ax.set_yticks(range(len(SETTINGS)))
    ax.set_yticklabels([s[0] for s in SETTINGS[::-1]])
    ax.set_xlabel("Saving vs night timer (DKK/year)")
    ax.set_xlim(0, None)
    ax.set_ylim(-0.6, len(SETTINGS) - 0.4)
    _clean(ax, "x")
    _save(fig, "fig_sensitivity")


def fig_hour_of_day():
    """When each policy uses electricity: mean spot price and mean shiftable load by time of day."""
    from common import N_STEPS, TZ, step_times
    from prices import PriceOracle
    plt, fig = _axes((3.5, 2.9))
    local = step_times(0, N_STEPS).tz_convert(TZ)
    q = (local.hour * 4 + local.minute // 15).to_numpy()
    hours = np.arange(96) / 4
    by_q = lambda v: pd.Series(v).groupby(q).mean().to_numpy()
    top, bottom = fig.subplots(2, 1, sharex=True, gridspec_kw={"height_ratios": [1, 1.8]})
    top.step(hours, by_q(PriceOracle().actual()), where="post", color=INK, lw=1.2)
    top.set_ylabel("Spot price\n(DKK/kWh)")
    top.set_ylim(0, None)
    _clean(top)
    for p in SHOWN:
        load_kw = np.mean([sum(np.load(RUNS / Config(h, p).name / "steps.npz").values()) for h in HOUSES], axis=0)
        bottom.step(hours, by_q(load_kw), where="post", color=COL[p], lw=1.4, label=LABEL[p])
    bottom.set_ylabel("Shiftable load\n(kW, mean)")
    bottom.set_xlabel("Time of day (Danish time)")
    bottom.set_xticks(range(0, 25, 3))
    bottom.set_xlim(0, 24)
    bottom.set_ylim(0, None)
    bottom.legend(frameon=False, loc="upper right", handlelength=1.2)
    _clean(bottom)
    _save(fig, "fig_hour_of_day")


main()
